import tempfile
import unittest
from pathlib import Path

from export_osv_runtime_lockfile import runtime_lockfile_content


class RuntimeLockfileExportTests(unittest.TestCase):
    def test_includes_only_exact_release_runtime_configuration(self):
        source = """# Generated by Gradle
androidx.core:core-ktx:1.19.1=debugRuntimeClasspath,releaseCompileClasspath,releaseRuntimeClasspath
org.test:compile-only:1.0=releaseCompileClasspath
org.test:instrumentation:2.0=debugAndroidTestRuntimeClasspath
org.test:lint-tool:3.0=androidLintTool,ktlint
empty=androidApis,androidJdkImage
"""
        result = runtime_lockfile_content(source)

        self.assertIn(
            "androidx.core:core-ktx:1.19.1=releaseRuntimeClasspath",
            result,
        )
        self.assertNotIn("org.test:compile-only", result)
        self.assertNotIn("org.test:instrumentation", result)
        self.assertNotIn("org.test:lint-tool", result)
        self.assertNotIn("empty=", result)

    def test_does_not_match_similar_configuration_names(self):
        source = """org.test:debug-name:1.0=debugReleaseRuntimeClasspath
org.test:release-name:2.0=releaseRuntimeClasspathExtra
"""
        with self.assertRaisesRegex(ValueError, "No dependencies were found"):
            runtime_lockfile_content(source)

    def test_rejects_malformed_lockfile_lines(self):
        with self.assertRaisesRegex(ValueError, "missing '=' separator"):
            runtime_lockfile_content("not-a-gradle-lock-entry")

    def test_rejects_invalid_module_coordinates(self):
        source = "org.test:missing-version=releaseRuntimeClasspath"
        with self.assertRaisesRegex(ValueError, "invalid Gradle module coordinate"):
            runtime_lockfile_content(source)

    def test_rejects_duplicate_runtime_coordinates(self):
        source = """org.test:duplicate:1.0=releaseRuntimeClasspath
org.test:duplicate:1.0=debugRuntimeClasspath,releaseRuntimeClasspath
"""
        with self.assertRaisesRegex(ValueError, "duplicate release runtime coordinate"):
            runtime_lockfile_content(source)

    def test_cli_style_output_is_sorted_and_contains_a_nonempty_scope(self):
        source = """org.z:second:2.0=releaseRuntimeClasspath
org.a:first:1.0=releaseRuntimeClasspath
"""
        result = runtime_lockfile_content(source)
        dependency_lines = [
            line for line in result.splitlines()
            if line and not line.startswith("#")
        ]

        self.assertEqual(
            [
                "org.a:first:1.0=releaseRuntimeClasspath",
                "org.z:second:2.0=releaseRuntimeClasspath",
            ],
            dependency_lines,
        )

    def test_rejects_empty_runtime_classpath(self):
        with self.assertRaisesRegex(ValueError, "No dependencies were found"):
            runtime_lockfile_content("# no dependencies\nempty=androidApis\n")

    def test_cli_writes_generated_file_to_parent_directory(self):
        from export_osv_runtime_lockfile import main

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "app" / "gradle.lockfile"
            destination = root / "build" / "osv" / "gradle.lockfile"
            source.parent.mkdir(parents=True)
            source.write_text(
                "org.test:runtime:1.0=releaseRuntimeClasspath\n",
                encoding="utf-8",
            )

            result = main(["--input", str(source), "--output", str(destination)])

            self.assertEqual(0, result)
            self.assertTrue(destination.is_file())
            self.assertIn(
                "org.test:runtime:1.0=releaseRuntimeClasspath",
                destination.read_text(encoding="utf-8"),
            )


if __name__ == "__main__":
    unittest.main()
